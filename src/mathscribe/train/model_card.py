"""Model card (``README.md``) for a trained adapter on the HF Hub.

The card is built from the run's ``run_info.json`` and from the eval results of the
adapter in ``reports/results/`` (the files whose ``run_name`` is the train run name).

``mathscribe.train.sft`` writes and pushes the card at the end of training (without eval
results). After the eval runs, build the card again and push it:

    python -m mathscribe.train.model_card --repo-id <user>/<repo> --push
    python -m mathscribe.train.model_card --run-info outputs/sft_base/run_info.json \\
        --out outputs/sft_base/README.md        # local only

Without ``--run-info``, the script downloads ``run_info.json`` from the Hub repo.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path
from typing import Any

from mathscribe.eval.leaderboard import _pct, _with_ci, load_results

log = logging.getLogger("mathscribe.model_card")

RUN_INFO = "run_info.json"


def _fmt_hours(seconds: float | None) -> str:
    return "-" if seconds is None else f"{seconds / 3600:.2f} h"


def eval_results_for(run_name: str, results_dir: str | Path) -> list[dict[str, Any]]:
    """The eval results of ``run_name``, sorted by test set name and N."""
    if not Path(results_dir).is_dir():
        return []
    found = [r for r in load_results(results_dir) if r.get("run_name") == run_name]
    return sorted(found, key=lambda r: (r["testset"]["name"], r["testset"]["n"]))


def _eval_section(results: list[dict[str, Any]], run_name: str) -> list[str]:
    lines = ["## Evaluation", ""]
    if not results:
        return [
            *lines,
            "No eval results yet. Run `python -m mathscribe.eval.run_eval` with "
            f"`run_name: {run_name}`, then build this card again "
            "(`python -m mathscribe.train.model_card --push`).",
            "",
        ]
    lines += [
        "Frozen test sets of the MathScribe repo. All rates are percentages, with 95% "
        "bootstrap intervals. Render match compares the MathJax renders of the prediction "
        "and the reference.",
        "",
        "| Test set | n | Exact | Norm. match | CER | Compile | Render match | Commit |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        m, ts = r["metrics"], r["testset"]
        commit = (r.get("git_commit") or "-")[:7] + ("+" if r.get("git_dirty") else "")
        lines.append(
            f"| `{ts['name']}` | {ts['n']} | {_pct(m.get('exact_match'))} "
            f"| {_with_ci(r, 'normalized_match')} | {_pct(m.get('cer'))} "
            f"| {_pct(m.get('compile_rate'))} | {_with_ci(r, 'render_match')} | `{commit}` |"
        )
    return [*lines, ""]


def build_model_card(
    info: dict[str, Any], results: list[dict[str, Any]], repo_id: str | None = None
) -> str:
    """The markdown model card of a train run (``run_info.json`` content + eval results)."""
    cfg = info["config"]
    model, lora, data, train = cfg["model"], cfg["lora"], cfg["data"], cfg["train"]
    validation = cfg.get("validation") or {}
    cost = info.get("cost") or {}
    wandb = info.get("wandb")
    repo_url = info.get("git_remote")
    commit = (info.get("git_commit") or "")[:7]
    title = repo_id or info["run_name"]

    front = [
        "---",
        f"base_model: {model['name']}",
        "library_name: peft",
        "pipeline_tag: image-text-to-text",
        "datasets:",
        f"- {data['dataset']}",
        "tags:",
        "- mathscribe",
        "- latex-ocr",
        "- lora",
        "- unsloth",
        "---",
        "",
    ]
    source = f"[MathScribe]({repo_url})" if repo_url else "MathScribe"
    intro = [
        f"# {title}",
        "",
        f"A LoRA adapter for `{model['name']}` that writes the LaTeX of a formula image. "
        f"It was trained with {source} (commit `{commit or '-'}`), run `{info['run_name']}`.",
        "",
        "<!-- Generated by `python -m mathscribe.train.model_card`. Do not edit by hand. -->",
        "",
    ]

    layers = [
        name
        for name, key in (
            ("vision", "finetune_vision_layers"),
            ("language", "finetune_language_layers"),
            ("attention", "finetune_attention_modules"),
            ("MLP", "finetune_mlp_modules"),
        )
        if lora.get(key)
    ]
    variant = "rsLoRA" if lora.get("use_rslora") else "LoRA"
    if lora.get("use_dora"):
        variant = "DoRA"
    batch = train.get("per_device_train_batch_size", 1) * train.get(
        "gradient_accumulation_steps", 1
    )
    if train.get("max_steps", -1) and train.get("max_steps", -1) > 0:
        length = f"`max_steps={train['max_steps']}`"
    else:
        length = f"{train.get('num_train_epochs', 3)} epoch(s)"
    excluded = ", ".join(f"`{Path(p).name}`" for p in data.get("exclude", [])) or "none"
    revision = (data.get("revision") or "main")[:8]

    precision = "4-bit QLoRA" if model["load_in_4bit"] else "16-bit"
    rows = [
        ("Base model", f"`{model['name']}` ({precision})"),
        (
            "Adapter",
            f"{variant}, r={lora['r']}, alpha={lora['lora_alpha']}, "
            f"dropout={lora['lora_dropout']}, layers: {', '.join(layers)}",
        ),
        (
            "Data",
            f"`{data['dataset']}` split `{data['split']}` @ `{revision}`, "
            f"{info.get('train_rows', '-')} rows (excluded manifests: {excluded})",
        ),
        (
            "Schedule",
            f"{length}, {info.get('global_step', '-')} steps done, batch {batch}, "
            f"lr {train.get('learning_rate')} ({train.get('lr_scheduler_type', 'linear')}), "
            f"optimizer `{train.get('optim', '-')}`, seed {train.get('seed', '-')}",
        ),
        (
            "Trainable params",
            f"{info.get('trainable_params', 0):,} of {info.get('total_params', 0):,}",
        ),
    ]
    if validation.get("manifest"):
        best = info.get("best_checkpoint") or {}
        metric = best.get("metric") or "eval_loss"
        value = best.get("value")
        value_text = "-" if value is None else f"{value:.4f}"
        samples = validation.get("samples") or "all"
        rows.append(
            (
                "Validation",
                f"`{Path(validation['manifest']).name}`, first {samples} rows. "
                f"Best {metric}: {value_text} (step {best.get('step', '-')}).",
            )
        )

    training = ["## Training", "", "| Item | Value |", "|---|---|"]
    training += [f"| {k} | {v} |" for k, v in rows]

    usd = cost.get("usd")
    price = (
        f"${usd:.2f} at ${cost['usd_per_hour']}/GPU-hour (public price, see "
        "`configs/gpu_prices.yaml`; the run used free Colab)"
        if usd is not None
        else "- (no public price for this GPU)"
    )
    compute = [
        "",
        "## Compute",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| GPU | {info.get('gpu', '-')} |",
        f"| Train time (all sessions) | "
        f"{_fmt_hours(info.get('total_train_s', info.get('wall_clock_s')))} |",
        f"| GPU hours | {cost.get('gpu_hours', '-')} |",
        f"| Cost | {price} |",
        f"| Peak reserved memory | {info.get('peak_reserved_memory_gb', '-')} GB |",
        "",
    ]
    tracking = ["## Tracking", ""]
    if wandb:
        run = f"[{wandb['id']}]({wandb['url']})" if wandb.get("url") else f"`{wandb['id']}`"
        tracking.append(f"- W&B run: {run}")
    tracking += [f"- `{RUN_INFO}` in this repo has the full config and the library versions.", ""]

    instruction = json.dumps(
        data.get("instruction", "Write the LaTeX representation for this image.")
    )
    usage = [
        "## Usage",
        "",
        "Use the same prompt as in training: the text, then the image, and no thinking.",
        "",
        "```python",
        "from PIL import Image",
        "from unsloth import FastVisionModel",
        "",
        f'model, processor = FastVisionModel.from_pretrained("{repo_id or "<repo>"}", '
        f"load_in_4bit={model['load_in_4bit']})",
        "FastVisionModel.for_inference(model)",
        "messages = [{",
        '    "role": "user",',
        f'    "content": [{{"type": "text", "text": {instruction}}}, {{"type": "image"}}],',
        "}]",
        "prompt = processor.apply_chat_template(",
        "    messages, add_generation_prompt=True, enable_thinking=False",
        ")",
        'image = Image.open("formula.png").convert("RGB")',
        "inputs = processor(images=[image], text=[prompt], add_special_tokens=False,",
        '                   return_tensors="pt").to(model.device)',
        "out = model.generate(**inputs, max_new_tokens=512, do_sample=False)",
        'print(processor.batch_decode(out[:, inputs["input_ids"].shape[1]:], '
        "skip_special_tokens=True)[0])",
        "```",
        "",
        "## Limitations",
        "",
        f"- The training data is `{data['dataset']}`: printed formulas with the im2latex "
        "tokenization (a space between tokens). The handwritten results (CROHME) show how "
        "the adapter does outside this domain.",
        "- The prompt must be the training prompt. `enable_thinking=False` is necessary: "
        "without it, the model starts a `<think>` block.",
        "",
    ]
    return "\n".join(
        front
        + intro
        + _eval_section(results, info["run_name"])
        + training
        + compute
        + tracking
        + usage
    )


def write_model_card(
    info: dict[str, Any],
    out: Path,
    results_dir: str | Path = "reports/results",
    repo_id: str | None = None,
    eval_run: str | None = None,
) -> Path:
    results = eval_results_for(eval_run or info["run_name"], results_dir)
    out.write_text(build_model_card(info, results, repo_id))
    log.info("Model card: %s (%d eval results)", out, len(results))
    return out


def push_model_card(path: Path, repo_id: str, message: str = "Update model card") -> None:
    from huggingface_hub import upload_file

    upload_file(
        path_or_fileobj=str(path), path_in_repo="README.md", repo_id=repo_id, commit_message=message
    )
    log.info("Pushed the model card to https://huggingface.co/%s", repo_id)


def download_run_info(repo_id: str, dest: Path) -> Path:
    from huggingface_hub import hf_hub_download

    return Path(hf_hub_download(repo_id, RUN_INFO, local_dir=dest))


def main(argv: list[str] | None = None) -> None:
    logging.basicConfig(
        level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s"
    )
    p = argparse.ArgumentParser(
        prog="mathscribe.train.model_card", description=__doc__.splitlines()[0]
    )
    p.add_argument("--repo-id", help="Hub repo of the adapter (run_info.json source, push target)")
    p.add_argument("--run-info", type=Path, help="Local run_info.json (default: from --repo-id)")
    p.add_argument("--results-dir", default="reports/results")
    p.add_argument("--eval-run", help="run_name of the eval results (default: the train run name)")
    p.add_argument("--out", type=Path, help="Output file (default: next to run_info.json)")
    p.add_argument("--push", action="store_true", help="Upload the card to --repo-id as README.md")
    args = p.parse_args(argv)

    if args.run_info is None and args.repo_id is None:
        p.error("give --run-info or --repo-id")
    if args.push and args.repo_id is None:
        p.error("--push needs --repo-id")
    run_info = args.run_info or download_run_info(
        args.repo_id, Path("outputs/model_cards") / args.repo_id
    )
    info = json.loads(Path(run_info).read_text())
    out = args.out or Path(run_info).with_name("README.md")
    write_model_card(info, out, args.results_dir, args.repo_id, args.eval_run)
    if args.push:
        push_model_card(out, args.repo_id)


if __name__ == "__main__":
    main()

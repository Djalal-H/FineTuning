"""Build ``reports/ablations.md`` from the committed ablation files. No GPU and no W&B key.

The inputs:
- ``configs/ablations.yaml``: the runs (name, factor, overrides) and the ``skipped`` list.
- ``reports/results/abl_<name>__<testset>_n<N>.json``: the val result of each run.
- ``reports/runs/abl_<name>.json``: the ``run_info.json`` of each run (GPU, time, memory, cost).

Usage:
    python -m mathscribe.ablation_report
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from mathscribe.ablations import SPEC, load_spec
from mathscribe.eval.leaderboard import (
    _delta_vs_baseline,
    _pct,
    _with_ci,
    is_significant,
    paired_delta,
)

TESTSET = "latex_ocr_val"
BASE_RUN = "base"
METRICS = {"normalized_match": "normalized match", "render_match": "render match"}

HEADER = """# Ablations (Phase 2)

<!-- Generated by `python -m mathscribe.ablation_report`. Do not edit by hand. -->

Each run changes one setting of
[`configs/train/ablation_base.yaml`](../configs/train/ablation_base.yaml). The list of runs is
in [`configs/ablations.yaml`](../configs/ablations.yaml). All runs use the same rows, seeds and
schedule. The runs are compared on the val set only, never on the test sets.
"""

HOW_TO_READ = """How to read the tables:

- `[low, high]` after a value is its 95% confidence interval (bootstrap, 2000 resamples).
- *Δ* is the value of the run minus the value of the base run, on the same rows (paired
  bootstrap). A `*` shows that the interval does not include 0 (significant at the 5% level).
- There are {k} comparisons for each metric. When there is no real difference, about 1
  comparison in 20 still gets a `*`. Treat one `*` alone as weak evidence.
- *eval_loss* is the lowest validation loss during training ({val_rows} val rows), from the
  checkpoint that became the adapter.
- *Train $* is the training time only, at the public price of the same GPU
  ([`configs/gpu_prices.yaml`](../configs/gpu_prices.yaml)). The runs used free GPUs, so this
  is not money spent. Each result JSON in [`results/`](results/) and each run file in
  [`runs/`](runs/) has the full values.
"""


def _load_json(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text()) if path.is_file() else None


def load_ablations(
    spec: dict[str, Any],
    results_dir: str | Path,
    runs_dir: str | Path,
    *,
    testset: str = TESTSET,
    eval_rows: int = 500,
    tag: str = "",
) -> list[dict[str, Any]]:
    """One entry for each run of the spec, in spec order: the spec row, its result, its run info."""
    suffix = f"_{tag}" if tag else ""
    out = []
    for run in spec["runs"]:
        name = f"abl_{run['name']}{suffix}"
        out.append(
            {
                "spec": run,
                "name": name,
                "result": _load_json(Path(results_dir) / f"{name}__{testset}_n{eval_rows}.json"),
                "info": _load_json(Path(runs_dir) / f"{name}.json"),
            }
        )
    return out


def _overrides(run: dict[str, Any]) -> str:
    return " ".join(f"`{o}`" for o in run.get("overrides", [])) or "-"


def _wandb(entry: dict[str, Any]) -> str:
    links = []
    for label, source in (("train", entry["info"]), ("eval", entry["result"])):
        url = ((source or {}).get("wandb") or {}).get("url")
        if url:
            links.append(f"[{label}]({url})")
    return " · ".join(links) or "-"


def _params(n: int | None) -> str:
    return "-" if n is None else f"{n / 1e6:.1f} M"


def _num(value: float | None, fmt: str) -> str:
    return "-" if value is None else format(value, fmt)


def _setup_line(base: dict[str, Any]) -> str:
    info, result = base["info"], base["result"]
    parts = []
    if info:
        cfg = info.get("config", {})
        train = cfg.get("train", {})
        batch = train.get("per_device_train_batch_size", 0) * train.get(
            "gradient_accumulation_steps", 0
        )
        parts.append(
            f"Base model `{cfg.get('model', {}).get('name', '-')}`, "
            f"{info.get('train_rows', '-'):,} train rows, {info.get('global_step', '-')} steps, "
            f"batch {batch}, learning rate {train.get('learning_rate', '-')}, "
            f"GPU {info.get('gpu', '-')}."
        )
    if result:
        ts = result["testset"]
        parts.append(
            f"Val set `{ts['name']}`, the first {ts['n']} rows (rows sha256 `{ts['sha256'][:16]}`)."
        )
    return " ".join(parts)


def _quality_table(entries: list[dict[str, Any]], baseline: dict[str, Any] | None) -> list[str]:
    lines = [
        "| Run | Setting | Override | Norm. match | Δ norm. | Render match | Δ render | CER "
        "| Compile | eval_loss | W&B |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        r, info, run = e["result"], e["info"] or {}, e["spec"]
        best = (info.get("best_checkpoint") or {}).get("value")
        if r is None:
            quality = "| - | - | - | - | - | - "
        else:
            quality = (
                f"| **{_with_ci(r, 'normalized_match')}** "
                f"| {_delta_vs_baseline(r, baseline, 'normalized_match')} "
                f"| **{_with_ci(r, 'render_match')}** "
                f"| {_delta_vs_baseline(r, baseline, 'render_match')} "
                f"| {_with_ci(r, 'cer')} | {_pct(r['metrics'].get('compile_rate'))} "
            )
        lines.append(
            f"| `{e['name']}` | {run['factor']} | {_overrides(run)} {quality}"
            f"| {_num(best, '.4f')} | {_wandb(e)} |"
        )
    return lines


def _significant(entries: list[dict[str, Any]], baseline: dict[str, Any] | None) -> list[str]:
    if baseline is None:
        return ["The base run has no result yet, so there is no comparison."]
    found = []
    for e in entries:
        if e["result"] is None or e["result"] is baseline:
            continue
        for metric, label in METRICS.items():
            delta = paired_delta(e["result"], baseline, metric)
            if is_significant(delta):
                d, lo, hi = delta
                word = "higher" if d > 0 else "lower"
                found.append(
                    f"- `{e['name']}` ({e['spec']['factor']}): {label} is {abs(100 * d):.1f} "
                    f"points {word} than the base run [{100 * lo:+.1f}, {100 * hi:+.1f}]."
                )
    if not found:
        return [
            "None. No run is different from the base run at the 5% level, on normalized "
            "match or on render match."
        ]
    return found


def _cost_table(entries: list[dict[str, Any]]) -> tuple[list[str], list[str]]:
    lines = [
        "| Run | Setting | Trainable params | Peak VRAM (GB) | s/step | Train GPU h | Train $ "
        "| Eval img/s | Commit |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    notes = []
    for e in entries:
        info, r = e["info"], e["result"]
        if info is None:
            lines.append(f"| `{e['name']}` | {e['spec']['factor']} | - | - | - | - | - | - | - |")
            continue
        cost = info.get("cost") or {}
        total_s, steps = info.get("total_train_s"), info.get("global_step")
        s_per_step = total_s / steps if total_s and steps else None
        peak = _num(info.get("peak_reserved_memory_gb"), ".2f")
        if info.get("resumed_from"):
            peak += "†"
            note = (
                f"- `{e['name']}`: the last session took {info.get('wall_clock_s', 0):,.0f} s of "
                f"{total_s or 0:,.0f} s training time."
            )
            if not info.get("best_checkpoint"):
                note += (
                    " The run file has no best checkpoint, so the adapter is the last checkpoint"
                    " and eval_loss is `-`."
                )
            notes.append(note)
        ips = ((r or {}).get("runtime") or {}).get("images_per_s")
        commit = (info.get("git_commit") or "-")[:7] + ("+" if info.get("git_dirty") else "")
        lines.append(
            f"| `{e['name']}` | {e['spec']['factor']} | {_params(info.get('trainable_params'))} "
            f"| {peak} | {_num(s_per_step, '.1f')} | {_num(cost.get('gpu_hours'), '.2f')} "
            f"| {_num(cost.get('usd'), '.2f')} | {_num(ips, '.2f')} | `{commit}` |"
        )
    if notes:
        notes = [
            "† The run continued from a Hub checkpoint in a new session. The peak VRAM is from "
            "the last session only, so it can be lower than the real training peak. The time "
            "and the cost count all sessions.",
            "",
            *notes,
        ]
    return lines, notes


def _skipped_table(spec: dict[str, Any]) -> list[str]:
    skipped = spec.get("skipped") or []
    if not skipped:
        return []
    lines = [
        "## Runs that were skipped",
        "",
        "These settings were tried and do not work. They are not in the tables above.",
        "",
        "| Run | Setting | Override | Reason |",
        "|---|---|---|---|",
    ]
    for run in skipped:
        reason = " ".join(str(run.get("reason", "-")).split())
        lines.append(f"| `{run['name']}` | {run['factor']} | {_overrides(run)} | {reason} |")
    return [*lines, ""]


def render_report(spec: dict[str, Any], entries: list[dict[str, Any]]) -> str:
    base = next((e for e in entries if e["spec"]["name"] == BASE_RUN), entries[0])
    baseline = base["result"]
    done = [e for e in entries if e["result"] is not None]
    missing = [e["name"] for e in entries if e["result"] is None or e["info"] is None]
    val_rows = ((base["info"] or {}).get("eval_rows")) or "-"

    lines = [HEADER]
    setup = _setup_line(base)
    if setup:
        lines += [setup, ""]
    lines += [HOW_TO_READ.format(k=max(len(done) - 1, 0), val_rows=val_rows)]

    lines += ["## Quality on the val set", "", *_quality_table(entries, baseline), ""]
    lines += ["## Differences from the base run", "", *_significant(entries, baseline), ""]
    cost, notes = _cost_table(entries)
    lines += ["## Cost and memory", "", *cost, ""]
    if notes:
        lines += [*notes, ""]
    lines += _skipped_table(spec)
    if missing:
        lines += [
            "## Runs with missing files",
            "",
            "These runs have no result JSON or no run file yet: "
            + ", ".join(f"`{m}`" for m in missing)
            + ".",
            "",
        ]
    return "\n".join(lines)


def write_report(
    spec_path: str | Path,
    results_dir: str | Path,
    runs_dir: str | Path,
    out: str | Path,
    *,
    testset: str = TESTSET,
    eval_rows: int = 500,
    tag: str = "",
) -> Path:
    spec = load_spec(spec_path)
    entries = load_ablations(
        spec, results_dir, runs_dir, testset=testset, eval_rows=eval_rows, tag=tag
    )
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_report(spec, entries))
    return out


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(
        prog="mathscribe.ablation_report", description=__doc__.split("\n")[0]
    )
    p.add_argument("--spec", default=SPEC)
    p.add_argument("--results-dir", default="reports/results")
    p.add_argument("--runs-dir", default="reports/runs")
    p.add_argument("--out", default="reports/ablations.md")
    p.add_argument("--testset", default=TESTSET)
    p.add_argument("--eval-rows", type=int, default=500)
    p.add_argument("--tag", default="", help="the run name suffix, for example 'smoke'")
    args = p.parse_args(argv)
    path = write_report(
        args.spec,
        args.results_dir,
        args.runs_dir,
        args.out,
        testset=args.testset,
        eval_rows=args.eval_rows,
        tag=args.tag,
    )
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
